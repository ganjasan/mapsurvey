"""Render the REST API reference page of the help centre from the OpenAPI document.

    python scripts/build_api_reference.py            # rewrite help/src/content/docs/reference/api.md
    python scripts/build_api_reference.py --check    # exit 1 when the page is stale

The document is the contract (`/api/v1/openapi.json`, generated by django-ninja from
the same pydantic schemas that validate requests), so the page is generated, never
edited by hand. `ApiReferenceFreshnessTest` runs the check in CI: a change to a route
or a schema without a regenerated page fails the suite.
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / 'help' / 'src' / 'content' / 'docs' / 'reference' / 'api.md'

HEADER = """---
title: REST API reference
description: Every endpoint of the Mapsurvey REST API v1 — paths, parameters, request and response fields, and the error codes each one returns.
sidebar:
  order: 55
---

<!-- Generated by scripts/build_api_reference.py from /api/v1/openapi.json. Do not edit by hand. -->

The machine-readable contract is [`/api/v1/openapi.json`](https://mapsurvey.org/api/v1/openapi.json)
(OpenAPI 3.1): load it into Postman, Insomnia or a client generator. This page is generated from it.
To make your first call, see [Use the REST API](/how-to/use-the-rest-api/).

**Base URL** `https://mapsurvey.org/api/v1` · **Authentication** `Authorization: Bearer <token>` —
a [personal token](/how-to/personal-tokens/) or an OAuth 2.1 access token · **Plan** the workspace
that owns the survey must be on [Pro](/reference/plans-and-billing/).

## Errors

Every error has the same shape: `{{"error": "<code>", "detail": "<text>", ...}}`. Switch on `error`;
`detail` is for people and may change. `validation` errors add `fields` (field name → messages),
and an unknown field in a request body is refused by name rather than ignored.

| Code | Status | Meaning |
|---|---|---|
{codes}

"""

CODE_ROWS = (
    ('invalid_token', 401, 'No bearer token, or one that is unknown, expired or revoked.'),
    ('scope_missing', 403, 'The token lacks the permission this call needs (`scope` names it).'),
    ('pro_required', 403, "The survey's workspace is not on Pro (`upgrade_url` links to its billing page)."),
    ('forbidden_role', 403, 'You can see the survey but your role on it is too low (`role` names the one needed).'),
    ('not_found', 404, 'Nothing there — or nothing you may see. The two are deliberately the same answer.'),
    ('validation', 422, 'The body or a parameter is invalid; `fields` lists what and why.'),
    ('draft_required', 409, 'A structural change to a live survey: start unpublished changes (`draft` is their uuid when they exist).'),
    ('answers_at_risk', 409, 'The delete would remove `count` answers; repeat with `acknowledge_answer_loss=true`.'),
    ('delete_blocked', 409, 'Something else depends on what you are deleting.'),
    ('translation_gaps', 409, 'Some languages are missing text; repeat with `acknowledge_translation_gaps: true`.'),
    ('incompatible_draft', 409, 'Unpublished changes conflict with collected answers; repeat with `force: true`.'),
    ('transition_refused', 409, 'The survey cannot move to that status from where it is.'),
    ('email_unconfirmed', 403, "The account has not confirmed its email address yet; publishing waits for it."),
    ('conflict', 409, 'The request conflicts with the current state (e.g. unpublished changes already exist).'),
    ('bad_cursor', 400, 'The pagination cursor is not valid for this list.'),
    ('method_not_allowed', 405, 'That HTTP method is not offered on this path (`Allow` lists the ones that are).'),
    ('rate_limited', 429, 'Too many calls; wait `Retry-After` seconds.'),
    ('server_error', 500, 'Our fault. It is logged; retrying later is safe for reads.'),
)


def _schema(doc, ref):
    return doc['components']['schemas'][ref.rsplit('/', 1)[-1]]


def _type(doc, s):
    if '$ref' in s:
        return s['$ref'].rsplit('/', 1)[-1]
    if 'anyOf' in s:
        kinds = [_type(doc, x) for x in s['anyOf'] if x.get('type') != 'null']
        return ' or '.join(kinds) + (' or null' if any(x.get('type') == 'null' for x in s['anyOf']) else '')
    if s.get('type') == 'array':
        return f"list of {_type(doc, s.get('items', {}))}"
    if 'enum' in s:
        return ' | '.join(f'`{v}`' for v in s['enum'])
    if 'const' in s:
        return f"`{s['const']}`"
    return s.get('format') or s.get('type') or 'object'


def _fields(doc, schema, seen=None):
    seen = seen or set()
    if '$ref' in schema:
        name = schema['$ref'].rsplit('/', 1)[-1]
        if name in seen:
            return []
        seen = seen | {name}
        schema = _schema(doc, schema['$ref'])
    rows = []
    required = set(schema.get('required', []))
    for name, prop in (schema.get('properties') or {}).items():
        desc = (prop.get('description') or '').replace('\n', ' ')
        rows.append(f"| `{name}` | {_type(doc, prop)} | {'yes' if name in required else ''} | {desc} |")
    return rows


def _body_schema(op):
    content = (op.get('requestBody') or {}).get('content') or {}
    for media in ('application/json', 'multipart/form-data'):
        if media in content:
            return content[media].get('schema')
    return None


def _ok_schema(op):
    for status, resp in sorted(op.get('responses', {}).items()):
        if status.startswith('2'):
            schema = ((resp.get('content') or {}).get('application/json') or {}).get('schema')
            return status, schema
    return None, None


def render(doc):
    codes = '\n'.join(f'| `{c}` | {s} | {m} |' for c, s, m in CODE_ROWS)
    out = [HEADER.format(codes=codes)]
    by_tag = {}
    for path, methods in doc['paths'].items():
        for method, op in methods.items():
            by_tag.setdefault((op.get('tags') or ['Other'])[0], []).append((path, method, op))
    for tag, ops in by_tag.items():
        out.append(f'## {tag}\n')
        for path, method, op in ops:
            short = path.replace('/api/v1', '')
            out.append(f'### `{method.upper()} {short}`\n')
            text = (op.get('description') or op.get('summary') or '').strip()
            if text:
                out.append(text + '\n')
            params = [p for p in op.get('parameters', []) if p.get('in') in ('path', 'query')]
            if params:
                out.append('| Parameter | In | Type | Required |\n|---|---|---|---|')
                for p in params:
                    out.append(f"| `{p['name']}` | {p['in']} | {_type(doc, p.get('schema', {}))} | {'yes' if p.get('required') else ''} |")
                out.append('')
            body = _body_schema(op)
            if body:
                rows = _fields(doc, body)
                if rows:
                    out.append('**Body**\n\n| Field | Type | Required | Notes |\n|---|---|---|---|')
                    out.extend(rows)
                    out.append('')
            status, ok = _ok_schema(op)
            if status:
                kind = _type(doc, ok) if ok else 'empty'
                out.append(f'**{status}** {kind if ok else "no body"}\n')
            errors = op.get('x-error-codes') or []
            if errors:
                out.append('Errors: ' + ', '.join(f'`{c}`' for c in errors) + '\n')
    schemas = doc.get('components', {}).get('schemas', {})
    out.append('## Objects\n')
    for name in sorted(schemas):
        if not name.endswith(('Out', 'List')):
            continue
        out.append(f'### {name}\n')
        out.append('| Field | Type | Always | Notes |\n|---|---|---|---|')
        out.extend(_fields(doc, {'$ref': f'#/components/schemas/{name}'}))
        out.append('')
    return '\n'.join(out).rstrip() + '\n'


def openapi_document():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'mapsurvey.settings')
    import django
    django.setup()
    from api.v1 import api
    return json.loads(json.dumps(api.get_openapi_schema(), default=str))


def main(argv):
    page = render(openapi_document())
    if '--check' in argv:
        current = PAGE.read_text() if PAGE.exists() else ''
        if current != page:
            print(f'{PAGE.relative_to(ROOT)} is stale: run python scripts/build_api_reference.py')
            return 1
        return 0
    PAGE.write_text(page)
    print(f'wrote {PAGE.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
