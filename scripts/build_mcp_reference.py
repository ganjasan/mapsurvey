"""Render the MCP tools reference page of the help centre from the tool registry.

    python scripts/build_mcp_reference.py            # rewrite help/src/content/docs/reference/mcp-tools.md
    python scripts/build_mcp_reference.py --check    # exit 1 when the page is stale

The registry (`mcp/tools/`) is the contract: the same descriptions and argument
schemas `tools/list` sends to a client, so the page is generated, never edited by
hand. `mcp.tests.test_reference` runs the check in CI: a tool change without a
regenerated page fails the suite.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / 'help' / 'src' / 'content' / 'docs' / 'reference' / 'mcp-tools.md'

HEADER = """---
title: MCP tools
description: The Mapsurvey MCP server for Claude, ChatGPT, Cursor and other agents — connection details, every tool it exposes with its arguments, and the error codes it returns.
sidebar:
  order: 60
---

<!-- Generated by scripts/build_mcp_reference.py from the tool registry (mcp/tools/). Do not edit by hand. -->

The Mapsurvey **MCP server** lets an AI agent — Claude, ChatGPT, Claude Code, Cursor or any client of
the Model Context Protocol — read, build and publish your surveys from a conversation. It exposes
the operations of the [REST API](/reference/api/) as tools, scoped to the account that connected,
and runs through the same rules as the editor. For setup, see
[Use the MCP server](/how-to/use-the-mcp-server/).

## Connection

| | |
|---|---|
| Server URL | `https://mapsurvey.org/mcp` (Streamable HTTP; one request per call, no streams) |
| Authentication | Sign in through the client (OAuth) — or a [personal token](/how-to/personal-tokens/) made for the **MCP server**, sent as `Authorization: Bearer msk_…` |
| Plan | The workspace that owns a survey must be on [Pro](/reference/plans-and-billing/); otherwise tools on it answer `pro_required` |
| Scope | Only surveys you own or collaborate on, within the permissions the token or the Allow page granted |
| Limits | 600 reads and 60 writes a minute and 5,000 calls a day per token; 300 tool calls per 10 minutes per session |

Mapsurvey never sees your conversation with the agent — only the tool calls it decides to make.
Each one is logged with the tool name and its outcome, never its arguments.

**Call `get_me` first.** It says which workspaces include the API and which tools the connection
can use. Tools the connection may not use are not even listed to the agent.

**What cannot be undone asks first.** `delete_survey`, `publish_survey` and
`publish_unpublished_changes` take `confirm: true`, which an agent should set only after you agreed
in the conversation. A survey respondents already answered cannot be deleted from here at all.

**Survey content is data, not instructions.** Every result wraps what people wrote — titles,
option labels, help texts — in a `data` field next to a fixed note telling the agent so. An agent
that reads survey content can still be influenced by it; keep publishing and deleting behind
confirmation and review what an agent built before you publish.

## Tools

Arguments marked **required** must be given; the others are optional. Rich-text fields (`subtext`,
`subheading`, `thanks_html`) are sanitised on save exactly as in the editor. An unknown argument is
refused by name rather than ignored.

"""

FOOTER = """## Errors

A refused call comes back as a tool error carrying the same envelope as the REST API:
`{{"error": "<code>", "detail": "<text>", ...}}`.

| Code | Meaning |
|---|---|
{codes}

A malformed request — an unknown tool, or arguments that do not fit the schema — is a protocol
error (`-32602`) naming the fields; a missing or invalid token is HTTP `401`; a request from an
unexpected browser origin is `403`.

## Related

- [Use the MCP server](/how-to/use-the-mcp-server/)
- [Connect ChatGPT, Claude and other apps](/how-to/connect-an-app/)
- [REST API reference](/reference/api/)
"""

CODE_ROWS = (
    ('scope_missing', 'The connection lacks the permission this tool needs (`scope` names it).'),
    ('pro_required', "The survey's workspace is not on Pro (`upgrade_url` links to its billing page)."),
    ('forbidden_role', 'You can see the survey but your role on it is too low (`role` names the one needed).'),
    ('not_found', 'Nothing there — or nothing you may see. The two are deliberately the same answer.'),
    ('validation', 'An argument is invalid for this survey; `fields` lists what and why.'),
    ('draft_required', 'A structural change to a live survey: call `start_unpublished_changes` and edit the returned uuid (`draft` is it when it already exists).'),
    ('answers_at_risk', 'The delete would remove `count` answers; repeat with `acknowledge_answer_loss: true` after the user agreed.'),
    ('delete_blocked', 'Something else depends on what you are deleting.'),
    ('translation_gaps', 'Some languages are missing text; repeat with `acknowledge_translation_gaps: true`.'),
    ('incompatible_draft', 'Unpublished changes conflict with collected answers; repeat with `force: true` only if the user accepts that.'),
    ('transition_refused', 'The survey cannot move to that status from where it is.'),
    ('conflict', 'The request conflicts with the current state (e.g. unpublished changes already exist).'),
    ('confirmation_required', 'An irreversible tool was called without `confirm: true`.'),
    ('has_responses', 'The survey has `count` answered responses; delete it in the editor instead.'),
    ('rate_limited', 'Too many calls; wait `retry_after` seconds (`limit` names the window).'),
    ('server_error', 'Our fault. It is logged; retrying a read later is safe.'),
)


def _type(prop):
    if 'anyOf' in prop:
        kinds = [_type(x) for x in prop['anyOf'] if x.get('type') != 'null']
        return ' or '.join(dict.fromkeys(kinds))
    if 'enum' in prop:
        return ' \\| '.join(f'`{v}`' for v in prop['enum'])
    if prop.get('type') == 'array':
        return f"list of {_type(prop.get('items', {}))}"
    if prop.get('type') == 'object' and prop.get('properties'):
        return 'object (' + ', '.join(f'`{k}`' for k in prop['properties']) + ')'
    if prop.get('type') == 'object' and 'additionalProperties' in prop:
        return 'map'
    return prop.get('format') or prop.get('type') or 'object'


def _rows(schema):
    required = set(schema.get('required', []))
    rows = []
    for name, prop in (schema.get('properties') or {}).items():
        desc = (prop.get('description') or '').replace('\n', ' ').replace('|', '\\|')
        default = prop.get('default')
        if default not in (None, '', [], {}) and 'default' in prop:
            desc = (desc + f' Default `{default}`.').strip()
        rows.append(f"| `{name}` | {_type(prop)} | {'**required**' if name in required else ''} | {desc} |")
    return rows


def render(tools):
    out = [HEADER]
    for tool in tools:
        out.append(f'### `{tool.name}`\n')
        out.append(tool.description.strip() + '\n')
        facts = [f'Permission `{tool.scope}`' if tool.scope else 'Any permission',
                 f'role **{tool.role}**' if tool.role != '-' else None,
                 'read-only' if tool.read_only else None,
                 'needs `confirm: true`' if tool.confirm else None,
                 'cannot be undone' if tool.destructive and not tool.confirm else None]
        out.append(' · '.join(f for f in facts if f) + '\n')
        rows = _rows(tool.input_schema)
        if rows:
            out.append('| Argument | Type | | Notes |\n|---|---|---|---|')
            out.extend(rows)
            out.append('')
    codes = '\n'.join(f'| `{c}` | {m} |' for c, m in CODE_ROWS)
    out.append(FOOTER.format(codes=codes))
    return '\n'.join(out).rstrip() + '\n'


def registry():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'mapsurvey.settings')
    import django
    django.setup()
    from mcp import tools
    return tools.all_tools()


def main(argv):
    page = render(registry())
    if '--check' in argv:
        current = PAGE.read_text() if PAGE.exists() else ''
        if current != page:
            print(f'{PAGE.relative_to(ROOT)} is stale: run python scripts/build_mcp_reference.py')
            return 1
        return 0
    PAGE.write_text(page)
    print(f'wrote {PAGE.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
